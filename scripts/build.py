#!/usr/bin/env python3
"""Generate the host plugins (hosts/) from the host-neutral core (core/).

    scripts/build.py           write hosts/
    scripts/build.py --check   fail if hosts/ differs from what core/ produces

The core is the source of truth: the skill, the slash commands, the launcher
(bin/run) and the pinned release. Each host gets what it
needs around them. Only the standard library is used.
"""
import json
import re
import shutil
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
CORE = ROOT / "core"
VERSION = (ROOT / "VERSION").read_text().strip()
DESCRIPTION = (
    "Your own LLM wiki: build, query and maintain a curated Markdown wiki of cited knowledge "
    "with Leaf's validated tools (search, cite, and an editor that rejects batches that "
    "break the wiki's conventions)."
)
AUTHOR = {"name": "Amoz Pay"}
COMMANDS = ["init", "ingest", "query", "lint"]

HEADER = "<!-- Generated by scripts/build.py from core/. Do not edit: change core/ and rebuild. -->\n"


def write(path: Path, text: str, executable: bool = False) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text)
    path.chmod(0o755 if executable else 0o644)


def copy(src: Path, dst: Path, executable: bool = False) -> None:
    write(dst, src.read_text(), executable)


def split_frontmatter(text: str):
    match = re.match(r"---\n(.*?)\n---\n(.*)", text, re.S)
    if not match:
        raise SystemExit("a core file has no frontmatter")
    return match.group(1), match.group(2)


def render_command(text: str, run: str, args: str) -> str:
    return text.replace("{{RUN}}", run).replace("{{ARGS}}", args)


def with_header(text: str) -> str:
    """Put the 'generated' note after the frontmatter, where it is not read as instructions."""
    front, body = split_frontmatter(text)
    return f"---\n{front}\n---\n{HEADER}{body}"


def build_claude_code(out: Path) -> None:
    base = out / "claude-code"
    manifest = {
        "name": "grove",
        "version": VERSION,
        "description": DESCRIPTION,
        "author": AUTHOR,
        "keywords": ["wiki", "knowledge-base", "grove", "markdown", "citations", "mcp"],
        "mcpServers": {
            "leaf": {
                "type": "stdio",
                "command": "${CLAUDE_PLUGIN_ROOT}/bin/run",
                "args": ["leaf-mcp-editor"],
            }
        },
    }
    write(base / ".claude-plugin" / "plugin.json", json.dumps(manifest, indent=2) + "\n")
    write(base / "skills" / "grove" / "SKILL.md", with_header((CORE / "skill" / "SKILL.md").read_text()))
    for name in COMMANDS:
        text = (CORE / "commands" / f"{name}.md").read_text()
        text = render_command(text, "${CLAUDE_PLUGIN_ROOT}/bin/run", "$ARGUMENTS")
        write(base / "commands" / f"{name}.md", with_header(text))
    copy(CORE / "bin" / "run", base / "bin" / "run", True)
    copy(CORE / "release.env", base / "release.env")


def build_hermes(out: Path) -> None:
    base = out / "hermes"
    front, body = split_frontmatter((CORE / "skill" / "SKILL.md").read_text())
    description = re.search(r"^description: (.*)$", front, re.M).group(1)
    commands = []
    for name in COMMANDS:
        text = (CORE / "commands" / f"{name}.md").read_text()
        cfront, cbody = split_frontmatter(text)
        title = re.search(r"^description: (.*)$", cfront, re.M).group(1)
        cbody = render_command(cbody, "<grove>/bin/run", "the user's request")
        commands.append(f"### {name}: {title}\n{cbody.rstrip()}\n")
    skill = (
        "---\n"
        "name: grove\n"
        f"description: {description}\n"
        f"version: {VERSION}\n"
        f"author: {AUTHOR['name']}\n"
        "platforms: [linux, macos]\n"
        "metadata:\n"
        "  hermes:\n"
        "    tags: [wiki, knowledge-base, research, notes, markdown, citations]\n"
        "    category: research\n"
        "---\n"
        f"{HEADER}{body.rstrip()}\n\n## Workflows\n\n"
        "Hermes has no slash commands for this skill: follow the matching workflow when the user asks for it.\n\n"
        + "\n".join(commands)
    )
    write(base / "skills" / "research" / "grove" / "SKILL.md", skill)
    config = (
        "# Add to ~/.hermes/config.yaml, then restart Hermes (or /reload-mcp).\n"
        "# Replace <grove> with the folder of this wrapper (hosts/hermes).\n"
        "mcp_servers:\n"
        "  leaf:\n"
        '    command: "<grove>/bin/run"\n'
        '    args: ["leaf-mcp-editor"]   # or "leaf-mcp" for a read-only server\n'
        "    env:\n"
        '      LEAF_WIKI: "/home/you/wiki"\n'
        "    timeout: 60\n"
    )
    write(base / "config.yaml.snippet", config)
    copy(CORE / "bin" / "run", base / "bin" / "run", True)
    copy(CORE / "release.env", base / "release.env")
    write(
        base / "README.md",
        f"{HEADER}# grove for Hermes\n\n"
        "NOT TESTED against a running Hermes: the MCP configuration format is the one in Hermes's own\n"
        "documentation (`mcp_servers` with `command`, `args`, `env`, `timeout`), but nothing here has been run in it.\n\n"
        "1. Copy `skills/research/grove/` to `~/.hermes/skills/research/grove/`.\n"
        "2. Add `config.yaml.snippet` to `~/.hermes/config.yaml`, with this folder's path and your wiki's.\n"
        "3. Restart Hermes. The first start downloads the pinned Leaf release (see `release.env`).\n"

    )


def build_marketplace(root: Path) -> None:
    marketplace = {
        "name": "grove",
        "description": "grove: build, query and maintain an LLM wiki through the Leaf MCP tools.",
        "owner": AUTHOR,
        "plugins": [
            {
                "name": "grove",
                "source": "./hosts/claude-code",
                "description": DESCRIPTION,
                "version": VERSION,
            }
        ],
    }
    write(root / ".claude-plugin" / "marketplace.json", json.dumps(marketplace, indent=2) + "\n")


def build_all(root: Path) -> None:
    hosts = root / "hosts"
    if hosts.exists():
        shutil.rmtree(hosts)
    build_claude_code(hosts)
    build_hermes(hosts)
    build_marketplace(root)


def tree(path: Path) -> dict:
    return {
        str(p.relative_to(path)): (p.read_bytes(), p.stat().st_mode & 0o111)
        for p in sorted(path.rglob("*"))
        if p.is_file()
    }


def main() -> int:
    if "--check" in sys.argv:
        with tempfile.TemporaryDirectory() as tmp:
            build_all(Path(tmp))
            have = tree(ROOT / "hosts")
            fresh_hosts = tree(Path(tmp) / "hosts")
            if fresh_hosts != have:
                changed = sorted(set(fresh_hosts) ^ set(have)) or sorted(
                    k for k in fresh_hosts if fresh_hosts[k] != have.get(k)
                )
                print("hosts/ is out of date; run scripts/build.py. Differs:", *changed, sep="\n  ")
                return 1
            market = (Path(tmp) / ".claude-plugin" / "marketplace.json").read_text()
            if market != (ROOT / ".claude-plugin" / "marketplace.json").read_text():
                print(".claude-plugin/marketplace.json is out of date; run scripts/build.py")
                return 1
        print("hosts/ is up to date")
        return 0
    build_all(ROOT)
    print("generated hosts/ and .claude-plugin/marketplace.json")
    return 0


if __name__ == "__main__":
    sys.exit(main())
