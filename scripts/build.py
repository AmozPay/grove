#!/usr/bin/env python3
"""Generate the host plugins (hosts/) from the host-neutral core (core/).

    scripts/build.py           write hosts/
    scripts/build.py --check   fail if hosts/ differs from what core/ produces

The core is the source of truth: the plugin's identity and MCP server (plugin.json),
the skill, the slash commands, the launcher (bin/run) and the pinned release. Each
host gets what it needs around them. Only the standard library is used.
"""
import json
import re
import shutil
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
CORE = ROOT / "core"
VERSION = (ROOT / "VERSION").read_text().strip()
CONFIG = json.loads((CORE / "plugin.json").read_text())
SERVER = CONFIG["mcp"]["server"]
BINARY = CONFIG["mcp"]["binary"]
COMMANDS = ["init", "ingest", "query", "lint"]

HEADER = "<!-- Generated by scripts/build.py from core/. Do not edit: change core/ and rebuild. -->\n"


def write(path: Path, text: str, executable: bool = False) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text)
    path.chmod(0o755 if executable else 0o644)


def copy(src: Path, dst: Path, executable: bool = False) -> None:
    write(dst, src.read_text(), executable)


def split_frontmatter(text: str):
    match = re.match(r"---\n(.*?)\n---\n(.*)", text, re.S)
    if not match:
        raise SystemExit("a core file has no frontmatter")
    return match.group(1), match.group(2)


def init_by_shell(run: str) -> str:
    return (
        "Run (a shell command; it knows where the wiki goes, and refuses a wiki that already has files):\n\n"
        f'   `{run} leaf editor init --domain "<domain>" --tag <tag1>,<tag2>`'
    )


def render_command(text: str, run: str, args: str, init: str = "") -> str:
    return text.replace("{{INIT}}", init or init_by_shell(run)).replace("{{RUN}}", run).replace("{{ARGS}}", args)


def with_header(text: str) -> str:
    """Put the 'generated' note after the frontmatter, where it is not read as instructions."""
    front, body = split_frontmatter(text)
    return f"---\n{front}\n---\n{HEADER}{body}"


def build_claude_code(out: Path) -> None:
    base = out / "claude-code"
    manifest = {
        "name": CONFIG["name"],
        "version": VERSION,
        "description": CONFIG["description"],
        "author": CONFIG["author"],
        "keywords": CONFIG["keywords"],
        "mcpServers": {
            SERVER: {"type": "stdio", "command": "${CLAUDE_PLUGIN_ROOT}/bin/run", "args": [BINARY]}
        },
    }
    write(base / ".claude-plugin" / "plugin.json", json.dumps(manifest, indent=2) + "\n")
    write(base / "skills" / "grove" / "SKILL.md", with_header((CORE / "skill" / "SKILL.md").read_text()))
    for name in COMMANDS:
        text = (CORE / "commands" / f"{name}.md").read_text()
        text = render_command(text, "${CLAUDE_PLUGIN_ROOT}/bin/run", "$ARGUMENTS")
        write(base / "commands" / f"{name}.md", with_header(text))
    copy(CORE / "bin" / "run", base / "bin" / "run", True)
    copy(CORE / "release.env", base / "release.env")


AGENT_PLUGIN_SCHEMA = "https://agent-plugins.org/schemas/1.0.0/%s.schema.json"

INIT_BY_USER = (
    "This host cannot run a command for you, and creating a wiki is a command, not a tool. Ask the user to run, "
    "in the folder this plugin is installed in:\n\n"
    '   `./bin/run leaf editor init --domain "<domain>" --tag <tag1>,<tag2>`\n\n'
    "   (it knows where the wiki goes, and refuses a wiki that already has files). Go on when they say it is done."
)


def build_agent_plugin(out: Path) -> None:
    """Agent Plugins v1 (https://agent-plugins.org): plugin.json, skills/ and mcp.json. Hermes loads it."""
    base = out / "agent-plugin"
    manifest = {
        "$schema": AGENT_PLUGIN_SCHEMA % "plugin",
        "name": CONFIG["name"],
        "version": VERSION,
        "description": CONFIG["description"],
        "author": CONFIG["author"],
        "homepage": CONFIG["homepage"],
        "keywords": CONFIG["keywords"],
    }
    write(base / "plugin.json", json.dumps(manifest, indent=2) + "\n")
    mcp = {
        "$schema": AGENT_PLUGIN_SCHEMA % "mcp",
        "mcpServers": {SERVER: {"type": "stdio", "command": "./bin/run", "args": [BINARY]}},
    }
    write(base / "mcp.json", json.dumps(mcp, indent=2) + "\n")
    front, body = split_frontmatter((CORE / "skill" / "SKILL.md").read_text())
    commands = []
    for name in COMMANDS:
        cfront, cbody = split_frontmatter((CORE / "commands" / f"{name}.md").read_text())
        title = re.search(r"^description: (.*)$", cfront, re.M).group(1)
        cbody = render_command(cbody, "./bin/run", "the user's request", INIT_BY_USER)
        commands.append(f"### {name}: {title}\n{cbody.rstrip()}\n")
    skill = (
        f"---\n{front}\n---\n{HEADER}{body.rstrip()}\n\n## Workflows\n\n"
        "This host has no slash commands: follow the matching workflow when the user asks for it.\n\n"
        + "\n".join(commands)
    )
    write(base / "skills" / CONFIG["name"] / "SKILL.md", skill)
    copy(CORE / "bin" / "run", base / "bin" / "run", True)
    copy(CORE / "release.env", base / "release.env")


def build_marketplace(root: Path) -> None:
    marketplace = {
        "name": CONFIG["name"],
        "description": "grove: build, query and maintain an LLM wiki through the Leaf MCP tools.",
        "owner": CONFIG["author"],
        "plugins": [
            {
                "name": CONFIG["name"],
                "source": "./hosts/claude-code",
                "description": CONFIG["description"],
                "version": VERSION,
            }
        ],
    }
    write(root / ".claude-plugin" / "marketplace.json", json.dumps(marketplace, indent=2) + "\n")


def build_all(root: Path) -> None:
    hosts = root / "hosts"
    if hosts.exists():
        shutil.rmtree(hosts)
    build_claude_code(hosts)
    build_agent_plugin(hosts)
    build_marketplace(root)


def tree(path: Path) -> dict:
    return {
        str(p.relative_to(path)): (p.read_bytes(), p.stat().st_mode & 0o111)
        for p in sorted(path.rglob("*"))
        if p.is_file()
    }


def main() -> int:
    if "--check" in sys.argv:
        with tempfile.TemporaryDirectory() as tmp:
            build_all(Path(tmp))
            have = tree(ROOT / "hosts")
            fresh_hosts = tree(Path(tmp) / "hosts")
            if fresh_hosts != have:
                changed = sorted(set(fresh_hosts) ^ set(have)) or sorted(
                    k for k in fresh_hosts if fresh_hosts[k] != have.get(k)
                )
                print("hosts/ is out of date; run scripts/build.py. Differs:", *changed, sep="\n  ")
                return 1
            market = (Path(tmp) / ".claude-plugin" / "marketplace.json").read_text()
            if market != (ROOT / ".claude-plugin" / "marketplace.json").read_text():
                print(".claude-plugin/marketplace.json is out of date; run scripts/build.py")
                return 1
        print("hosts/ is up to date")
        return 0
    build_all(ROOT)
    print("generated hosts/ and .claude-plugin/marketplace.json")
    return 0


if __name__ == "__main__":
    sys.exit(main())
